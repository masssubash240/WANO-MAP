export function searchBot(query) {
  const q = query.toLowerCase().trim();
  if (!q) return null;

  // Try exact match in keywords or event name
  let best = null;
  let bestScore = -1;

  for (const item of botKnowledge) {
    if (item.event.toLowerCase().includes(q)) {
      return item;
    }
    for (const kw of item.keywords) {
      if (q === kw) {
        return item;
      }
      if (q.includes(kw) || kw.includes(q)) {
        const score = kw.length;
        if (score > bestScore) {
          bestScore = score;
          best = item;
        }
      }
    }
  }

  // Partial word search
  if (!best) {
    const words = q.split(/\s+/).filter((w) => w.length >= 2);
    for (const item of botKnowledge) {
      for (const kw of item.keywords) {
        for (const word of words) {
          if (kw.includes(word) || item.venue.toLowerCase().includes(word) || (item.coordinator && item.coordinator.toLowerCase().includes(word))) {
            return item;
          }
        }
      }
    }
  }

  return best;
}
